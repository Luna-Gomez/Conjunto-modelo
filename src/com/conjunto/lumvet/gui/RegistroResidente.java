    private void limpiarCampos(){
        txtNombreResidente.setText("");
        txtNumDocResidente.setText("");
        cmbTipoDocResidente.setSelectedIndex(0);
        numBloque.setValue(0);
        numCasa.setValue(0);
    }
    
    private void btnRegistroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistroActionPerformed
        try{
            Residente residente = new Residente();
            residente.setNombre(txtNombreResidente.getText());
            residente.setTipoDoc((String) cmbTipoDocResidente.getSelectedItem());
            residente.setNumDoc(txtNumDocResidente.getText());
            
            if((int) numCasa.getValue() > 100){
                numCasa.setValue(100);      
            }
            if ((int)numBloque.getValue() > 100) {
                numBloque.setValue(100);
            }
            
            residente.setNumBloque((int)numBloque.getValue());
            residente.setNumCasa((int)numCasa.getValue());
            
            boolean exito = registro.registrar(residente);
            if(exito){
                JOptionPane.showMessageDialog(this, "Residente " + residente.getNombre() + " registrado con éxito.");
            }
        } catch(NumberFormatException nfe){
            JOptionPane.showMessageDialog(this, "La Casa y el Bloque deben ser númericos");
        } catch(SQLException sqle){
            JOptionPane.showMessageDialog(this, "Error al intentar registrar en la base de datos: " + sqle.getMessage());
        } finally{
            limpiarCampos();
        }
    }//GEN-LAST:event_btnRegistroActionPerformed

