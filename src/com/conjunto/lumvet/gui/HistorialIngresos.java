    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String numDoc = txtSearchDocument.getText().trim();
        if(numDoc.isEmpty()){
            cargarHistorial();
            return;
        }
        
        IHistorialIngresoDAO historialIngresoDAO = new HistorialIngresoDAOImpl();
        try{
            List<HistorialIngresoDTO> resultados = historialIngresoDAO.buscarPorDocumento(numDoc);
            llenarTabla(resultados);
            if(resultados.isEmpty()){
                JOptionPane.showMessageDialog(this, "No se encontraron registros para el documento " + numDoc + ".");
            }
        } catch (SQLException sqle){
            JOptionPane.showMessageDialog(this, "Error al buscar en el historial: " + sqle.getMessage());
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnRegistrarSalidaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarSalidaActionPerformed
        String numDoc = txtSearchDocument.getText().trim();
        if(numDoc.isEmpty()){
            JOptionPane.showMessageDialog(this, "Ingrese el número de documento de quién sale.");
            return;
        }
        
        IHistorialIngresoDAO historialIngresoDAO = new HistorialIngresoDAOImpl();
        
        try{
            if(historialIngresoDAO.registrarSalida(numDoc)){
                JOptionPane.showMessageDialog(this, "Salida registrada correctamente");
                btnBuscar.doClick();
            }else{
                JOptionPane.showMessageDialog(this, "No hay ingreso en estado \"Dentro\" para el documento " + numDoc + ".");
            }
        } catch (SQLException sqle){
            JOptionPane.showMessageDialog(this, "Error al registrar la salida: " + sqle.getMessage());
        }
    }//GEN-LAST:event_btnRegistrarSalidaActionPerformed


