    private void cargarHistorial(){
        IHistorialIngresoDAO historialIngresoDAO = new HistorialIngresoDAOImpl();
        try{
            llenarTabla(historialIngresoDAO.obtenerHistorial());
        } catch (SQLException sqle){
            JOptionPane.showMessageDialog(this, "Error al cargar el historial: " + sqle.getMessage());
        }
    }
    
    private void llenarTabla(List<HistorialIngresoDTO> lista){
        
        DefaultTableModel tablaModel = new DefaultTableModel();
        tablaModel.addColumn("Fecha y Hora");
        tablaModel.addColumn("Tipo Usuario");
        tablaModel.addColumn("Nombre");
        tablaModel.addColumn("N° Documento");
        tablaModel.addColumn("Detalle");
        tablaModel.addColumn("Hora de Salida");
        tablaModel.addColumn("Estado");
        
        for (HistorialIngresoDTO historial : lista) {
            tablaModel.addRow(new Object[]{
                historial.getFechaHora(), historial.getTipoUser(), historial.getNombre(), historial.getNumDoc(), historial.getDetalle(), historial.getHoraSalida(), historial.getEstado()
            });
        }
        
        tablaHistorialIngresos.setModel(tablaModel);
        int[] anchos  = {110, 85, 110, 95, 160, 110, 65};
        for(int i = 0; i < anchos.length; i++){
            tablaHistorialIngresos.getColumnModel().getColumn(i).setPreferredWidth(anchos[i]);
        }
    }
    
