    private void btnIngresoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresoActionPerformed
        String tipoUser = (String) cmbTipoPersona.getSelectedItem();
        try{
            boolean exito;
            switch (tipoUser){
                case "Residente":
                    exito = controlador.ingresoResidente(txtNumDocR.getText());
                    if(!exito){
                        JOptionPane.showMessageDialog(this, "No se pudo encontrar el número de documento"+ txtNumDocR.getText() +" en la base de datos, por favor verifique el documento de identidad.", "¡INGRESO DENEGADO!", JOptionPane.WARNING_MESSAGE);
                        limpiarCamposResidente();
                    }
                    break;
                case "Trabajador":
                    exito = controlador.ingresoTrabajador(txtNombreT.getText(), (String) cmbTipoDocT.getSelectedItem(), txtNumDocT.getText(), txtEmpresaT.getText(), txtCargoT.getText());
                    if(!exito){
                        JOptionPane.showMessageDialog(this, "No se registró el ingreso del Trabajador, porfavor valide los datos ingresados.", "¡INGRESO DENEGADO!", JOptionPane.WARNING_MESSAGE);
                        limpiarCamposTrabajador();
                    }
                    break;
                case "Proveedor":
                    exito = controlador.ingresoProveedor(txtNombreP.getText(), (String) cmbTipoDocP.getSelectedItem(), txtNumDocP.getText(), txtEmpresaP.getText());
                    if(!exito){
                        JOptionPane.showMessageDialog(this, "No se registró el ingreso del Proveedor, por favor valide los datos ingresados.", "¡INGRESO DENEGADO!", JOptionPane.WARNING_MESSAGE);
                        limpiarCamposProveedor();
                    }
                    break;
                case "Visitante":
                    exito = controlador.ingresoVisitante(txtNombreV.getText(), (String) cmbTipoDocV.getSelectedItem(), txtNumDocV.getText(), txtNumDocVisitado.getText());
                    if(!exito){
                        JOptionPane.showMessageDialog(this, "No se registró el ingreso del visitante, por favor valide los datos ingresados.", "¡INGRESO DENEGADO!", JOptionPane.WARNING_MESSAGE);
                        limpiarCamposVisitante();
                    }
                    break;
                default:
                    exito = false;
            }
            
            if(exito){
                JOptionPane.showMessageDialog(this, "Ingreso registrado correctamente.");
                limpiarTodosCampos();
            }
            
        }catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error en la base de datos: " + e.getMessage());
        }
    }//GEN-LAST:event_btnIngresoActionPerformed

